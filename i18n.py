from i18n_storefront import STOREFRONT

for _lang, _extras in STOREFRONT.items():
    _UI.setdefault(_lang, dict(_UI["en"]))
    _UI[_lang].update(_extras)

for _code in LANGUAGES:
    if _code not in _UI:
        _UI[_code] = dict(_UI["en"])
    for _key, _value in STOREFRONT["en"].items():
        _UI[_code].setdefault(_key, _value)


def translate(key, language="en", **kwargs):
    table = _UI.get(language) or _UI["en"]
    text = table.get(key) or _UI["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def currency_for_country(country_code, default="EUR"):
    return COUNTRY_CODE_TO_CURRENCY.get((country_code or "").upper(), default)


def language_for_country(country_code):
    return COUNTRY_CODE_TO_LANGUAGE.get((country_code or "").upper(), "")


def language_from_accept_header(header):
    for part in (header or "").split(","):
        code = part.split(";")[0].strip().lower().replace("_", "-")
        if not code:
            continue
        if code in LANGUAGES:
            return code
        primary = code.split("-")[0]
        if primary in LANGUAGES:
            return primary
    return ""
